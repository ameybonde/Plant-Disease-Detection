import json
from pathlib import Path

import numpy as np
import streamlit as st
import tensorflow as tf
from PIL import Image, ImageOps

APP_DIR = Path(__file__).resolve().parent
MODEL_PATH = APP_DIR / "plant_disease_prediction_model.keras"
CLASS_PATH = APP_DIR / "class_indices.json"
IMAGE_SIZE = (224, 224)  

st.set_page_config(
    page_title="Plant Disease Detection",
    page_icon="🌿",
    layout="wide",
)

@st.cache_resource
def load_model():
    if not MODEL_PATH.exists():
        raise FileNotFoundError(
            f"Model not found: {MODEL_PATH.name}. Put the .keras file beside app.py."
        )
    return tf.keras.models.load_model(MODEL_PATH)

@st.cache_data
def load_class_names():
    if not CLASS_PATH.exists():
        raise FileNotFoundError(
            f"Class mapping not found: {CLASS_PATH.name}. "
            "Run the notebook cell that saves class_indices.json and copy the file here."
        )
    with open(CLASS_PATH, "r", encoding="utf-8") as f:
        mapping = json.load(f)
    # JSON object keys are strings; the notebook saves index -> class name.
    mapping = {int(index): name for index, name in mapping.items()}
    return [mapping[i] for i in sorted(mapping)]

def preprocess_image(image: Image.Image) -> np.ndarray:
    # Notebook preprocessing: RGB, resize to 224x224, float32, divide by 255.
    image = ImageOps.exif_transpose(image).convert("RGB")
    image = image.resize(IMAGE_SIZE)
    arr = np.asarray(image, dtype=np.float32) / 255.0
    return np.expand_dims(arr, axis=0)

st.title("Plant Disease Detection")
st.write(
    "Upload a clear photo of a plant leaf. The trained CNN will predict "
    "the most likely class from the classes it learned during training."
)

with st.sidebar:
    st.header("About the model")
    st.write("CNN trained on PlantVillage images.")
    st.write("Input size: 224 × 224 RGB")
    st.write("Preprocessing: pixel values scaled to 0–1")
    st.caption("Predictions are model estimates, not a substitute for expert diagnosis.")

uploaded_file = st.file_uploader(
    "Choose a leaf image",
    type=["jpg", "jpeg", "png", "webp"],
)

if uploaded_file is not None:
    try:
        image = Image.open(uploaded_file)
        
        # Split screen into Left (Image + Button) and Right (Results)
        col_img, col_pred = st.columns([1, 1], gap="medium")

        with col_img:
            st.image(image, caption="Uploaded leaf image", width=260)
            run_prediction = st.button("Predict disease", type="primary", use_container_width=True)

        with col_pred:
            if run_prediction:
                with st.spinner("Analyzing image..."):
                    model = load_model()
                    class_names = load_class_names()
                    batch = preprocess_image(image)
                    probabilities = np.asarray(model.predict(batch, verbose=0))[0]

                    if len(probabilities) != len(class_names):
                        st.error(
                            "The number of model outputs does not match class_indices.json. "
                            "Use the class_indices.json generated by this exact notebook/model."
                        )
                    else:
                        top_indices = np.argsort(probabilities)[::-1][:3]
                        top_idx = int(top_indices[0])
                        top_name = class_names[top_idx].replace("___", " — ").replace("_", " ")
                        top_conf = float(probabilities[top_idx]) * 100

                        st.subheader("Prediction")

                        CONFIDENCE_THRESHOLD = 85.0

                        if top_conf >= CONFIDENCE_THRESHOLD:
                            st.success(f"**{top_name}**")
                            st.metric("Model confidence", f"{top_conf:.2f}%")
                        else:
                            st.warning("The model is uncertain between multiple classes.")
                            st.write(f"Most likely: **{top_name}** ({top_conf:.2f}%)")

                            st.subheader("Possible Matches")
                            for idx in top_indices:
                                prob = float(probabilities[int(idx)])
                                if prob >= 0.05:
                                    name = class_names[int(idx)].replace("___", " — ").replace("_", " ")
                                    st.write(f"**{name}** — {prob * 100:.2f}%")
                                    st.progress(float(np.clip(prob, 0.0, 1.0)))

                        st.caption(
                            "Confidence is derived from the model's softmax output and does not guarantee clinical accuracy."
                        )
            else:
                st.info("Click **Predict disease** to evaluate the image.")

    except Exception as exc:
        st.error(f"Could not process the image or load the model: {exc}")
        st.info(
            "Check that the .keras model and class_indices.json are in the same folder "
            "as app.py, and that TensorFlow is installed in the active environment."
        )
else:
    st.info("Upload a JPG, JPEG, PNG, or WEBP image to begin.")
